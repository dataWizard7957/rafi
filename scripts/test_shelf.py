def main():
    if len(sys.argv) > 1:
        image_path = sys.argv[1]
    else:
        image_path = "scripts/test_shelf_image.jpg"
        _make_minimal_jpeg(image_path)

    print(f"Uploading {image_path} to {API}/uploads/shelf?direct=true …\n")
    with open(image_path, "rb") as f:
        resp = requests.post(
            f"{API}/uploads/shelf",
            params={"direct": "true"},
            files={"photo": ("shelf.jpg", f, "image/jpeg")},
            timeout=60,
        )

    if not resp.ok:
        print(f"ERROR {resp.status_code}: {resp.text}")
        sys.exit(1)

    data = resp.json()
    print(f"Status:  {data.get('status')}")
    print(f"Scan ID: {data.get('scan_id')}")

    if data.get("status") == "retake":
        print(f"Message: {data.get('message')}")
        print(f"Avg confidence: {data.get('avg_confidence')}")
        print("\nOK retake path works (low-confidence photo correctly rejected)")
        return

    detections = data.get("detections", [])
    drift = data.get("drift", [])
    low = data.get("low", [])

    print(f"\nDetections ({len(detections)}):")
    for d in detections:
        print(f"  {d['item']:30s}  count={d['count']:3d}  confidence={d['confidence']:.2f}")

    print(f"\nDrift items ({len(drift)})  [rule: |photo-system|>3 OR >30% of system]:")
    for d in drift:
        diff = abs(d["photoQty"] - d["systemQty"])
        ratio = diff / d["systemQty"] if d["systemQty"] else 0
        print(f"  {d['item']:30s}  system={d['systemQty']}  photo={d['photoQty']}"
              f"  diff={diff}  ratio={ratio:.0%}  "
              f"{'units' if diff > 3 else ''}{'ratio' if ratio > 0.3 else ''}")

    print(f"\nLow items ({len(low)})  [rule: photo_qty < 30% of par]:")
    for l in low:
        print(f"  {l['item']:30s}  photoQty={l['photoQty']}  par={l['par']}")

    print("\nOK shelf scan endpoint works")


if __name__ == "__main__":
    main()
